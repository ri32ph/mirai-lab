// Generate the search index from the same extraction rules as the browser.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {DOMParser} from 'linkedom';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const hub=fs.readFileSync(path.join(root,'qa-hub.js'),'utf8');
const definitions=hub.slice(hub.indexOf('const sources='),hub.indexOf('function chip('));
const context=vm.createContext({document:{querySelector:()=>null}});
vm.runInContext(definitions,context);
const sources=vm.runInContext('sources',context);
let bytes=0,articles=0;
for(const [field,urls] of Object.entries(sources)){
 for(const url of urls){
  const html=fs.readFileSync(path.join(root,url),'utf8');
  bytes+=Buffer.byteLength(html);articles++;
  context.sourceDocument=new DOMParser().parseFromString(html,'text/html');
  context.sourceUrl=url;context.sourceField=field;
  if(field==='symptoms'){context.symptomArticle=JSON.parse(html);vm.runInContext('extractSymptom(symptomArticle)',context);}else vm.runInContext('extract(sourceDocument,sourceUrl,sourceField)',context);
 }
}
const items=vm.runInContext(`items.sort((a,b)=>a.field.localeCompare(b.field)||a.url.localeCompare(b.url)||a.id.localeCompare(b.id));items`,context);
// Normalize once while generating; search does only substring comparisons.
const labels=vm.runInContext('labels',context);
for(const item of items){item.searchKey=[item.q,item.a,item.title,item.searchText||'',...item.tags,labels[item.field]].join(' ').normalize('NFKC').toLowerCase();delete item.searchText;}
const output='// Generated by npm run build:qa-index. Do not edit.\nwindow.MIRAI_QA_INDEX = '+JSON.stringify(items).replace(/</g,'\\u003c')+';\n';
fs.writeFileSync(path.join(root,'qa-index.js'),output);
console.log(JSON.stringify({articles,items:items.length,sourceBytes:bytes,indexBytes:Buffer.byteLength(output)}));
